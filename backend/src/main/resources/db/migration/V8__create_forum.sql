CREATE TABLE forum_discussions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_id VARCHAR(36) NOT NULL
        REFERENCES games(id) ON DELETE CASCADE,
    author_id BIGINT NOT NULL
        REFERENCES app_user(id) ON DELETE CASCADE,
    title VARCHAR(120) NOT NULL,
    description VARCHAR(2000) NOT NULL,
    cover_image BYTEA NOT NULL,
    cover_image_content_type VARCHAR(50) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_forum_discussions_title
        CHECK (char_length(trim(title)) BETWEEN 1 AND 120),
    CONSTRAINT chk_forum_discussions_description
        CHECK (char_length(trim(description)) BETWEEN 1 AND 2000)
);

CREATE INDEX idx_forum_discussions_created_at
    ON forum_discussions(created_at DESC);

CREATE INDEX idx_forum_discussions_game_id
    ON forum_discussions(game_id);

CREATE TABLE forum_replies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    discussion_id BIGINT NOT NULL
        REFERENCES forum_discussions(id) ON DELETE CASCADE,
    author_id BIGINT NOT NULL
        REFERENCES app_user(id) ON DELETE CASCADE,
    parent_reply_id BIGINT
        REFERENCES forum_replies(id) ON DELETE CASCADE,
    content VARCHAR(3000) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_forum_replies_content
        CHECK (char_length(trim(content)) BETWEEN 1 AND 3000)
);

CREATE INDEX idx_forum_replies_discussion_created
    ON forum_replies(discussion_id, created_at);

CREATE TABLE forum_ratings (
    discussion_id BIGINT NOT NULL
        REFERENCES forum_discussions(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL
        REFERENCES app_user(id) ON DELETE CASCADE,
    rating SMALLINT NOT NULL CHECK (rating BETWEEN 1 AND 5),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (discussion_id, user_id)
);

CREATE TABLE forum_discussion_tags (
    discussion_id BIGINT NOT NULL
        REFERENCES forum_discussions(id) ON DELETE CASCADE,
    tag_id BIGINT NOT NULL
        REFERENCES tags(id) ON DELETE CASCADE,
    PRIMARY KEY (discussion_id, tag_id)
);