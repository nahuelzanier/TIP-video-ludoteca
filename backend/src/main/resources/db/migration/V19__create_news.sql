CREATE TABLE noticias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_id BIGINT NOT NULL
        REFERENCES app_user(id) ON DELETE CASCADE,
    title VARCHAR(150) NOT NULL,
    description VARCHAR(3000) NOT NULL,
    published_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    has_image BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT chk_noticias_title CHECK (char_length(trim(title)) BETWEEN 1 AND 150),
    CONSTRAINT chk_noticias_description CHECK (char_length(trim(description)) BETWEEN 1 AND 3000)
);

CREATE INDEX idx_noticias_published_at ON noticias(published_at DESC, id DESC);

CREATE INDEX idx_noticias_author_id ON noticias(author_id);

CREATE TABLE noticia_images (
    noticia_id BIGINT PRIMARY KEY
        REFERENCES noticias(id) ON DELETE CASCADE,
    content_type VARCHAR(50) NOT NULL,
    content BYTEA NOT NULL
);
